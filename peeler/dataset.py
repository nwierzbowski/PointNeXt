"""PeelerDataset - All-gold soup generation for sparse Top-K peeler training.

Takes per-mesh TBO data (256 emb + 16 transform per fragment)
and generates soups by mixing assets together. Every fragment in
the soup belongs to a real asset. No dense O(N²) ground truth — 
the model competes over K sparse candidates per node.

Each TBO file represents a scene. Assets are grouped by scene (TBO file)
and soups are generated by picking a scene and sampling assets from it.

Registered with openpoints DATASETS registry.
"""
import numpy as np
import torch
from collections import Counter, defaultdict
from torch.utils.data import Dataset

from openpoints.dataset.build import DATASETS
from .training.validate import FRAGMENT_RANGES
from .scene_joiner import SceneJoiner, compute_asset_scale, compute_asset_centroid, TRANSLATION_COLS
from .scene_splitter import SceneSplitter

# Pool building config
SAMPLES_PER_EPOCH = 2000
MAX_REPEATS = 16
MAX_BUCKET_SIZE = 5000


def _frag_to_range_key(frag: int) -> str:
    """Map fragment count to range key string."""
    n = len(FRAGMENT_RANGES)
    for i, ((low, high), range_key) in enumerate(FRAGMENT_RANGES):
        if i == n - 1:
            if low <= frag <= high:
                return range_key
        else:
            if low <= frag < high:
                return range_key
    return 'other'


@DATASETS.register_module()
class PeelerDataset(Dataset):
    """Unified dataset for peeler train/val.

    Generates samples by picking a scene (TBO file) and concatenating all
    its assets. Each sample is a "soup" of N fragments with an N x N ground
    truth matrix Y where Y_ij=1 if fragments i and j belong to the same asset.

    Args:
        mode: 'train' or 'val'
        all_embeddings: list of numpy arrays, one per asset, shape (N_i, 256)
        all_transforms: list of numpy arrays, one per asset, shape (N_i, 16)
        asset_to_file: list mapping asset_idx -> scene_idx (scene = TBO file)
        max_fragments: int, maximum total fragments per soup
        seed: int, random seed for reproducibility
        asset_dropout_prob: float, probability of triggering an asset dropout burst (0 = disabled, only effective in train mode)
        burst_prob: float, binomial p for burst size (default 0.5, burst=1 is 50%, burst=2 is 25%, etc.)
        asset_swap_prob: float, probability of swapping an asset's embedding with one of equal fragment count (0 = disabled)
    """

    def __init__(
        self,
        mode,
        all_embeddings,
        all_transforms,
        asset_to_file,
        max_fragments,
        seed,
        asset_dropout_prob=0.0,
        burst_prob=0.5,
        asset_swap_prob=0.0,
    ):
        assert mode in ('train', 'val'), f"Invalid mode: {mode}"
        self.mode = mode
        self.all_embeddings = all_embeddings  # list of (N_i, 256)
        self.all_transforms = all_transforms  # list of (N_i, 16)
        self.asset_to_file = asset_to_file  # list of int: asset_idx -> scene_idx
        self.max_fragments = max_fragments
        self.seed = seed
        self.asset_dropout_prob = asset_dropout_prob
        self.burst_prob = burst_prob
        self.asset_swap_prob = asset_swap_prob
        self._epoch = 0

        # Fragment count buckets: fragment_count -> [asset_indices]
        self._fragment_buckets = defaultdict(list)
        for asset_idx, emb in enumerate(all_embeddings):
            self._fragment_buckets[len(emb)].append(asset_idx)

        # Group asset indices by scene
        self._scene_assets = defaultdict(list)
        for asset_idx, scene_idx in enumerate(asset_to_file):
            self._scene_assets[scene_idx].append(asset_idx)

        # Sub-scene tracking
        self._scene_is_sub = {}
        self._scene_parent = {}
        self._scene_bucket = {}

        # Join tracking (training only)
        self._scene_is_joined = {}
        self._scene_sources = {}

        # Bucket scene counts (for capping)
        self._bucket_counts = Counter()

        # Build bucket mapping for raw scenes (before split/join)
        self._bucket_scenes = defaultdict(list)
        for scene_idx in self._scene_assets:
            if scene_idx in self._scene_bucket:
                bucket_key = self._scene_bucket[scene_idx]
            else:
                asset_indices = self._scene_assets[scene_idx]
                total_frags = sum(len(self.all_embeddings[aid]) for aid in asset_indices)
                actual_n = min(total_frags, self.max_fragments)
                bucket_key = _frag_to_range_key(actual_n)
            self._bucket_scenes[bucket_key].append(scene_idx)
            self._bucket_counts[bucket_key] += 1

        # Split scenes into sub-scenes for smaller buckets (training only)
        if mode == 'train':
            SceneSplitter(self._scene_assets, self._scene_is_sub,
                          self._scene_parent, self._scene_bucket,
                          self._bucket_scenes, self._bucket_counts,
                          self.all_embeddings, self.max_fragments, mode).run()

        # Join small scenes into larger scenes for bigger buckets (training only)
        if mode == 'train':
            SceneJoiner(self.all_transforms, [bk for _, bk in FRAGMENT_RANGES],
                        self.all_embeddings,
                        scene_assets=self._scene_assets,
                        scene_is_joined=self._scene_is_joined,
                        scene_sources=self._scene_sources,
                        scene_bucket=self._scene_bucket,
                        bucket_scenes=self._bucket_scenes,
                        bucket_counts=self._bucket_counts,
                        scene_is_sub=self._scene_is_sub).run(self.max_fragments)

        # Sorted list of all scenes (original + sub-scenes + joined)
        self._sorted_scenes = sorted(self._scene_assets.keys())
        self._num_scenes = len(self._sorted_scenes)

        self._epoch_pool = None

    def get_bucket_stats(self):
        """Return formatted bucket stats string for logging."""
        all_buckets = [item[1] for item in FRAGMENT_RANGES]
        lines = ['[Dataset] Scenes per bucket (raw / split / join / total):']
        total_raw = 0
        total_split = 0
        total_join = 0
        for bk in all_buckets:
            raw = 0
            split = 0
            join = 0
            for scene_idx in self._bucket_scenes.get(bk, []):
                if scene_idx in self._scene_is_joined:
                    join += 1
                elif scene_idx in self._scene_is_sub:
                    split += 1
                else:
                    raw += 1
            t = raw + split + join
            if raw > 0 or split > 0 or join > 0:
                lines.append(f'  {bk:>8}: {raw:>5} raw + {split:>5} split + {join:>5} join = {t:>5} total')
                total_raw += raw
                total_split += split
                total_join += join
        total_all = total_raw + total_split + total_join
        lines.append(f'  {"TOTAL":>8}: {total_raw:>5} raw + {total_split:>5} split + {total_join:>5} join = {total_all:>5} total')
        return '\n'.join(lines)

    def _get_scene_bucket(self, scene_idx):
        """Get the bucket key for a scene, computing it if not pre-assigned."""
        if scene_idx in self._scene_bucket:
            return self._scene_bucket[scene_idx]
        asset_indices = self._scene_assets[scene_idx]
        total_frags = sum(len(self.all_embeddings[a]) for a in asset_indices)
        return _frag_to_range_key(total_frags)

    def set_epoch(self, epoch: int):
        """Set the epoch and build a uniform pool across all buckets.

        Args:
            epoch: Current training epoch number (for randomization seed)
        """
        self._epoch = epoch

        if self.mode != 'train':
            self._epoch_pool = self._sorted_scenes[:]
            return

        # Uniform sampling: equal samples from each non-empty bucket
        active_buckets = [bk for _, bk in FRAGMENT_RANGES if self._bucket_scenes.get(bk)]
        num_buckets = len(active_buckets)
        samples_per_bucket = SAMPLES_PER_EPOCH // num_buckets

        pool = []
        pool_rng = np.random.RandomState(self.seed + epoch)
        for bucket_key in active_buckets:
            scenes = self._bucket_scenes[bucket_key]
            draws = [scenes[pool_rng.randint(0, len(scenes))] for _ in range(samples_per_bucket)]
            counts = Counter(draws)
            capped = []
            for scene, count in counts.items():
                capped.extend([scene] * min(count, MAX_REPEATS))
            pool.extend(capped)

        pool_rng.shuffle(pool)
        self._epoch_pool = pool if pool else self._sorted_scenes[:]

    def __len__(self):
        if self._epoch_pool is not None:
            return len(self._epoch_pool)
        return self._num_scenes

    def __getitem__(self, idx):
        # Pick scene from epoch pool (uniform bucket mixture) or sorted scenes (default)
        if self._epoch_pool is not None:
            scene_idx = self._epoch_pool[idx % len(self._epoch_pool)]
        else:
            scene_idx = self._sorted_scenes[idx % self._num_scenes]
        scene_asset_indices = self._scene_assets[scene_idx]

        # Use all assets from the scene (each contributes all its fragments)
        chosen_asset_indices = sorted(scene_asset_indices)

        # RNG for asset dropout and swap (deterministic per sample)
        if self.mode == 'train' and (self.asset_dropout_prob > 0 or self.asset_swap_prob > 0):
            dropout_rng = np.random.RandomState(self.seed + idx + self._epoch * 100000)

        # Collect embeddings and transforms from chosen assets with burst dropout and swap
        soup_emb_list = []
        soup_trans_list = []
        asset_ids_list = []
        asset_fragments = []

        new_local_id = 0
        i = 0
        while i < len(chosen_asset_indices):
            asset_gid = chosen_asset_indices[i]

            # Burst dropout (training only): check if this asset triggers a dropout burst
            if self.mode == 'train' and self.asset_dropout_prob > 0:
                if dropout_rng.random() < self.asset_dropout_prob:
                    # Roll burst size: geometric distribution (burst=0 is 50%, burst=1 is 25%, etc.)
                    burst_size = dropout_rng.geometric(p=self.burst_prob)
                    # Skip this asset + burst_size additional consecutive assets
                    i += 1 + burst_size
                    continue

            emb = self.all_embeddings[asset_gid]
            trans = self.all_transforms[asset_gid]
            n_fragments = len(emb)

            # Asset swap (training only): replace embedding and normalize transform to original's space
            if self.mode == 'train' and self.asset_swap_prob > 0:
                if dropout_rng.random() < self.asset_swap_prob:
                    bucket = self._fragment_buckets.get(n_fragments)
                    if bucket and len(bucket) > 1:
                        replacement_gid = bucket[dropout_rng.randint(0, len(bucket))]
                        emb = self.all_embeddings[replacement_gid]

                        # Compute original and replacement asset's scale and centroid
                        orig_scale = compute_asset_scale(trans)
                        orig_centroid = compute_asset_centroid(trans)

                        rep_trans = self.all_transforms[replacement_gid]
                        rep_scale = compute_asset_scale(rep_trans)
                        rep_centroid = compute_asset_centroid(rep_trans)

                        # Normalize replacement to canonical space, apply original's transform
                        if rep_scale > 1e-6:
                            new_trans = trans.copy()
                            # Normalize translation, apply original's scale and centroid
                            new_trans[:, TRANSLATION_COLS] = (
                                (rep_trans[:, TRANSLATION_COLS] - rep_centroid) / rep_scale
                            ) * orig_scale + orig_centroid
                            # Normalize rotation, apply original's scale
                            rot_cols = (0, 1, 2, 4, 5, 6, 8, 9, 10)
                            new_trans[:, rot_cols] = (
                                rep_trans[:, rot_cols] / rep_scale
                            ) * orig_scale
                            trans = new_trans

            soup_emb_list.append(emb)
            soup_trans_list.append(trans)
            asset_ids_list.append(np.full(n_fragments, new_local_id, dtype=np.int64))
            asset_fragments.append(n_fragments)
            new_local_id += 1
            i += 1

        # Fallback: if all assets were dropped, use all of them
        if len(soup_emb_list) == 0:
            for local_asset_id, asset_gid in enumerate(chosen_asset_indices):
                emb = self.all_embeddings[asset_gid]
                trans = self.all_transforms[asset_gid]
                n_fragments = len(emb)
                soup_emb_list.append(emb)
                soup_trans_list.append(trans)
                asset_ids_list.append(np.full(n_fragments, local_asset_id, dtype=np.int64))
                asset_fragments.append(n_fragments)

        soup_emb = np.concatenate(soup_emb_list, axis=0)
        soup_trans = np.concatenate(soup_trans_list, axis=0)
        asset_ids = np.concatenate(asset_ids_list, axis=0)

        # Truncate to max_fragments if scene is too large
        n = len(soup_emb)
        if n > self.max_fragments:
            trunc_rng = np.random.RandomState(self.seed + idx)
            keep = trunc_rng.choice(n, self.max_fragments, replace=False)
            keep.sort()
            soup_emb = soup_emb[keep]
            soup_trans = soup_trans[keep]
            asset_ids = asset_ids[keep]
            n = self.max_fragments

        if self.mode == 'train':
            # Shuffle soup
            rng = np.random.RandomState(self.seed + idx + self._epoch * 100000)
            shuffle_idx = rng.permutation(len(soup_emb))
            soup_emb = soup_emb[shuffle_idx]
            soup_trans = soup_trans[shuffle_idx]
            asset_ids = asset_ids[shuffle_idx]

        actual_n = len(soup_emb)

        return {
            'embeddings': torch.from_numpy(soup_emb),
            'transforms': torch.from_numpy(soup_trans),
            'asset_ids': torch.from_numpy(asset_ids),
            'soup_count': len(asset_fragments),
            'soup_stats': {
                'num_assets': len(asset_fragments),
                'avg_fragments': sum(asset_fragments) / len(asset_fragments) if asset_fragments else 0,
                'asset_fragments': list(asset_fragments),
                'target_n': self.max_fragments,
                'actual_n': actual_n,
            },
        }

    def compute_stats(self, num_samples=None):
        """Compute dataset statistics by iterating samples once.

        Args:
            num_samples: Number of samples to process. None = entire dataset.

        Returns:
            (asset_counts, asset_fragments, actual_ns) tuples for histogram widget
        """
        asset_counts = []
        asset_fragments = []
        actual_ns = []
        n = num_samples or len(self)
        for i in range(n):
            sample = self[i]
            stats = sample.get('soup_stats', {})
            if stats:
                asset_counts.append(stats['num_assets'])
                asset_fragments.append(tuple(stats['asset_fragments']))
                actual_ns.append(stats['actual_n'])
        return asset_counts, asset_fragments, actual_ns

    @staticmethod
    def collate_fn(datas):
        """Collate function for PeelerDataset.

        Flattens all scenes in the batch into single tensors (no padding).
        scene_ids tracks which nodes belong to which scene.
        """
        embeddings_list, transforms_list, asset_ids_list, scene_ids_list = [], [], [], []

        for i, d in enumerate(datas):
            n = len(d['embeddings'])

            embeddings_list.append(d['embeddings'])
            transforms_list.append(d['transforms'])
            asset_ids_list.append(d['asset_ids'])
            scene_ids_list.append(torch.full((n,), i, dtype=torch.int64))

        return {
            'embeddings': torch.cat(embeddings_list),
            'transforms': torch.cat(transforms_list),
            'asset_ids': torch.cat(asset_ids_list),
            'scene_ids': torch.cat(scene_ids_list),
            'soup_stats': [d['soup_stats'] for d in datas],
        }
